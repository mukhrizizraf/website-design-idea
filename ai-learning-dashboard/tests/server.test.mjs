import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { createServer } from '../server.mjs';
const token='test-only-token-with-at-least-24-characters';
test('API auth, validation, durable concurrent writes, CORS and static isolation',async()=>{
  const dataDir=await mkdtemp(join(tmpdir(),'practice-test-'));
  const server=createServer({token,dataDir,allowedOrigin:'https://example.github.io'});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const headers={Authorization:`Bearer ${token}`,'Content-Type':'application/json'};
  try{
    assert.equal((await fetch(base)).status,200);
    const script=await fetch(base+'/dashboard.js');
    assert.equal(script.status,200);
    assert.match(script.headers.get('content-type'),/javascript/);
    assert.match(await script.text(),/Generated by scripts\/bundle/);
    assert.equal((await fetch(base+'/api/lessons')).status,401);
    assert.equal((await fetch(base+'/api/lessons',{headers:{...headers,Origin:'https://evil.example'}})).status,403);
    assert.equal((await fetch(base+'/api/lessons',{headers:{...headers,Origin:'https://example.github.io'}})).headers.get('access-control-allow-origin'),'https://example.github.io');
    assert.equal((await fetch(base+'/api/lessons',{method:'POST',headers,body:'{}'})).status,400);
    assert.equal((await fetch(base+'/data/lessons.json')).status,404);
    const results=await Promise.all(Array.from({length:6},(_,i)=>fetch(base+'/api/lessons',{method:'POST',headers,body:JSON.stringify({title:`Lesson ${i}`})})));
    assert.ok(results.every(r=>r.status===201));
    assert.equal((await (await fetch(base+'/api/lessons',{headers})).json()).lessons.length,6);
    const restarted=createServer({token,dataDir});await new Promise(resolve=>restarted.listen(0,'127.0.0.1',resolve));
    try{assert.equal((await (await fetch(`http://127.0.0.1:${restarted.address().port}/api/lessons`,{headers})).json()).lessons.length,6);}finally{await new Promise(resolve=>restarted.close(resolve));}
  }finally{await new Promise(resolve=>server.close(resolve));await rm(dataDir,{recursive:true,force:true});}
});
test('MCP bridge initializes and delivers a lesson end to end',async()=>{
  const dataDir=await mkdtemp(join(tmpdir(),'practice-bridge-test-'));const server=createServer({token,dataDir});await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const child=spawn(process.execPath,['bridge.mjs'],{env:{...process.env,DASHBOARD_URL:base,DASHBOARD_TOKEN:token},stdio:['pipe','pipe','pipe']});
  const lines=createInterface({input:child.stdout})[Symbol.asyncIterator]();
  async function call(id,method,params){child.stdin.write(JSON.stringify({jsonrpc:'2.0',id,method,params})+'\n');return JSON.parse((await lines.next()).value);}
  try{
    assert.equal((await call(1,'initialize',{protocolVersion:'2025-11-25'})).result.serverInfo.name,'practice-lessons');
    assert.equal((await call(2,'tools/list')).result.tools[0].name,'save_lesson');
    const result=await call(3,'tools/call',{name:'save_lesson',arguments:{title:'From chat',summary:'A real bridge test',category:'Writing'}});
    assert.equal(JSON.parse(result.result.content[0].text).saved,true);
    assert.equal((await (await fetch(base+'/api/lessons',{headers:{Authorization:`Bearer ${token}`}})).json()).lessons[0].title,'From chat');
  }finally{child.stdin.end();child.kill();await new Promise(resolve=>server.close(resolve));await rm(dataDir,{recursive:true,force:true});}
});
