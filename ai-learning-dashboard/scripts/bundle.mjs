import { readFile, writeFile, rename } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
const root=new URL('../',import.meta.url);
export async function bundle(){
  const model=(await readFile(new URL('public/model.js',root),'utf8')).replace(/^export /gm,'');
  const app=(await readFile(new URL('public/app.js',root),'utf8')).replace(/^import .*?;\s*/,'');
  const output=`// Generated by scripts/bundle.mjs. Edit model.js and app.js instead.\n(()=>{\n'use strict';\n${model}\n${app}\n})();\n`;
  const destination=new URL('public/dashboard.js',root);
  try { if(await readFile(destination,'utf8')===output)return; } catch(e) { if(e.code!=='ENOENT')throw e; }
  const temporary=new URL(`public/dashboard.${randomUUID()}.tmp`,root);
  await writeFile(temporary,output,'utf8');
  await rename(temporary,destination);
}
await bundle();
